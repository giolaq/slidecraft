import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, readFile, readdir, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { validate, saveDeck, readDeck } from '../src/deck.js';
import { render } from '../src/render.js';
import { serve } from '../src/server.js';

const example = JSON.parse(await readFile(new URL('../examples/demo.deck.json', import.meta.url), 'utf8'));
test('validates sample and rejects malformed layouts, duplicate IDs, and missing content', () => {
  assert.deepEqual(validate(example), []);
  const bad = structuredClone(example);
  bad.slides[1].id = bad.slides[0].id;
  bad.slides[2].cards = [{ title: 'Incomplete' }];
  bad.slides[3].layout = 'unknown';
  assert.match(validate(bad).join('\n'), /duplicated/);
  assert.match(validate(bad).join('\n'), /body/);
  assert.match(validate(bad).join('\n'), /layout/);
  assert.ok(validate({ version: 1, title: 'Empty', slides: [] }).length);
});
test('escapes text and embedded JSON while preserving intentional custom markup', () => {
  const deck = structuredClone(example);
  deck.title = '</title><script>alert(1)</script>';
  deck.slides[0].title = '<img src=x onerror=alert(1)>';
  deck.slides[0].notes = '</script><script>alert(2)</script>';
  deck.slides[0].html = '<svg aria-label="A diagram"></svg>';
  const output = render(deck);
  assert.ok(!output.includes('<title></title><script>'));
  assert.ok(!output.includes('<img src=x'));
  assert.ok(!output.includes('</script><script>alert(2)'));
  assert.ok(output.includes('<svg aria-label="A diagram">'));
  const embedded = output.match(/<script id="deck-data" type="application\/json">(.*?)<\/script>/s)[1];
  assert.deepEqual(JSON.parse(embedded), deck);
});
test('writes validated decks atomically and preserves previous versions', async t => {
  const dir = await mkdtemp(join(tmpdir(), 'slidecraft-'));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const file = join(dir, 'deck.json');
  await saveDeck(file, example);
  const changed = { ...example, title: 'A new title' };
  await saveDeck(file, changed);
  assert.equal((await readDeck(file)).title, changed.title);
  const folder = join(dir, '.slidecraft-history', 'deck.json');
  const snapshots = await readdir(folder);
  assert.equal(snapshots.length, 1);
  assert.equal(JSON.parse(await readFile(join(folder, snapshots[0]), 'utf8')).title, example.title);
  await assert.rejects(() => saveDeck(file, { ...changed, slides: [] }));
  assert.equal((await readDeck(file)).title, changed.title);
});
test('HTTP editing rejects stale revisions, malformed decks, and unauthorized writes', async t => {
  const dir = await mkdtemp(join(tmpdir(), 'slidecraft-http-'));
  const file = join(dir, 'deck.json');
  await saveDeck(file, example);
  const server = await serve(file, 0);
  t.after(async () => { await new Promise(r => server.close(r)); await rm(dir, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const editor = await (await fetch(base)).text();
  const token = editor.match(/const token = '([^']+)'/)[1];
  const initial = await (await fetch(base + '/api/deck')).json();
  const request = (payload, headers = {}) => fetch(base + '/api/deck', { method: 'PUT', headers: { 'Content-Type': 'application/json', 'X-Slidecraft-Token': token, ...headers }, body: JSON.stringify(payload) });
  assert.equal((await request(initial, { 'X-Slidecraft-Token': 'wrong' })).status, 403);
  assert.equal((await request(initial, { Origin: 'https://example.com' })).status, 403);
  assert.equal((await request({ ...initial, deck: { ...initial.deck, slides: [] } })).status, 400);
  const changed = { ...initial, deck: { ...initial.deck, title: 'Edited through HTTP' } };
  const outcomes = await Promise.all([request(changed), request(changed)]);
  assert.deepEqual(outcomes.map(x => x.status).sort(), [200, 409]);
  assert.equal((await readDeck(file)).title, 'Edited through HTTP');
  assert.equal((await request(initial)).status, 409);
  const exported = await fetch(base + '/export');
  assert.match(exported.headers.get('content-disposition'), /attachment/);
  assert.match(await exported.text(), /Edited through HTTP/);
  assert.equal((await fetch(base + '/../../etc/passwd')).status, 404);
});
